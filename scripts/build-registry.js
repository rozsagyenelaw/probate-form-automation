// Regenerates lib/formgen/forms/all.js from the files in lib/formgen/forms.
const fs = require('fs'); const path = require('path');
const dir = path.join(__dirname, '../lib/formgen/forms');
const ids = fs.readdirSync(dir).filter((f) => f.endsWith('.js') && f !== 'all.js').map((f) => f.replace(/\.js$/, '')).sort();
const body = `// Generated by scripts/build-registry.js. Do not edit by hand.\nmodule.exports = {\n${ids.map((id) => `  '${id}': require('./${id}'),`).join('\n')}\n};\n`;
fs.writeFileSync(path.join(dir, 'all.js'), body);
console.log(ids.join(' '));
